export function getPersona(slug: string) {
  return personas.find((persona) => persona.slug === slug);
}

export function getPersonaBySlug(slug: string) {
  return personas.find((persona) => persona.slug === slug);
}

export function getPersonas() {
  return personas;
}

export function getFeaturedPersonas() {
  return personas.filter((persona) => persona.isFeatured);
}

export function searchPersonas(query: string) {
  const normalized = query.trim().toLowerCase();

  if (!normalized) {
    return personas;
  }

  return personas.filter((persona) => {
    const searchable = [
      persona.name,
      persona.profession,
      persona.category,
      persona.description,
      persona.shortDescription,
      persona.tags.join(" "),
      persona.expertise.join(" "),
      persona.biography,
    ]
      .join(" ")
      .toLowerCase();

    return searchable.includes(normalized);
  });
}

